def build():
    rng=random.Random(SEED)
    documents=[]
    for (domain, topic), items in TOPICS.items():
        # 4 documents per topic; each uses 9 of 12 authored sentences.
        # Rotated windows reduce, but do not eliminate, sentence reuse.
        for part in range(4):
            indexes=list(range(len(items)))
            rng.shuffle(indexes)
            picked=indexes[:9]
            sentences=[items[i] for i in picked]
            surface=''.join(s for s,_,_ in sentences)
            reading=''.join(r for _,r,_ in sentences)
            roma=''.join(x for _,_,x in sentences)
            assert len(roma)>250 and surface.count('ー')==reading.count('ー')==roma.count('-')
            assert romanize(reading)==roma
            documents.append(dict(id=f'{len(documents)+1:03d}',domain=domain,topic=topic,split='holdout' if part==3 else 'development',text=surface,reading_hiragana=reading,romaji=roma,character_count=len(surface),keystrokes=len(roma),long_marks=roma.count('-'),source_sentence_ids=picked))
    return dict(version=2,seed=SEED,kind='SYNTHETIC_AUTOGENERATED_FROM_ORIGINAL_SENTENCE_BANK',disclaimer='Authored sentences selected and recombined reproducibly. Not random sampling of real contemporary Japanese. Sentences repeat across documents within the same topic. Held-out document split is not independent at sentence-source level; do not treat as independent generalization evidence.',romaji_policy='Legacy original project si/ti/tu/hu/zi; original kana reading; dash(ー) preserved as ASCII -; IME conversion excluded.',domains=list(dict.fromkeys(d for d,t in TOPICS)),documents=documents,unique_source_sentences={f'{d}/{t}':len(x) for (d,t),x in TOPICS.items()})

def main():
    package=build();out=ROOT/'data/synthetic_three_domains.json';out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(package,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    for domain in package['domains']:
        documents=[d for d in package['documents'] if d['domain']==domain]
        n=sum(d['keystrokes'] for d in documents);long=sum(d['long_marks'] for d in documents)
        print(f'{domain:10} {len(documents)} documents {n} keys  {long} dashes ({long/n*100:.2f}%)')
    print('Total',len(package['documents']),'documents;',sum(d['keystrokes'] for d in package['documents']),'keystrokes;',sum(len(s) for s in TOPICS.values()),'source sentences')
    print('Saved',out)
if __name__=='__main__':main()
