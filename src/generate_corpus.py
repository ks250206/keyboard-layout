TOPICS = {}

def add(domain, topic, raw):
    lines = [line.strip() for line in raw.strip().splitlines() if line.strip()]
    items = []
    for line in lines:
        if line.count('|') != 1: raise ValueError(f'{domain}/{topic}: {line}')
        surface, reading = [x.strip() for x in line.split('|')]
        if not (surface.endswith('。') and reading.endswith('。')): raise ValueError(line)
        if surface.count('ー') != reading.count('ー'): raise ValueError(f'long mark discrepancy: {line}')
        rom = romanize(reading)
        if not (rom.endswith('.') and rom.count('-') == surface.count('ー')): raise ValueError(f'bad romanization {line} -> {rom}')
        items.append((surface, reading, rom))
    if len(items) < 10: raise ValueError(f'{domain}/{topic}: {len(items)} sentences')
    TOPICS[(domain, topic)] = items

